const CITY_KO = { Busan: '부산', Daegu: '대구', Incheon: '인천', Gwangju: '광주', Daejeon: '대전' };
const onePart = (part) => {
  if (LINE_KO[part]) return LINE_KO[part];
  let m = part.match(/^Line (\d)$/);
  if (m) return m[1] + '호선';
  m = part.match(/^(Busan|Daegu|Incheon|Gwangju|Daejeon)(?: Metro)? Line (\d)$/);
  if (m) return CITY_KO[m[1]] + ' ' + m[2] + '호선';
  return null;
};

export const koStation = (name) => STATION_KO[name] ?? null;
// Every part known, or nothing: half a line name in each language reads
// worse than one.
export function koLine(line) {
  if (typeof line !== 'string' || !line) return null;
  const parts = line.split(' / ').map(onePart);
  return parts.every(Boolean) ? parts.join(' · ') : null;
}
